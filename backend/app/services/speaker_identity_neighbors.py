"""
Speaker Identity Nearest-Neighbor Diagnostic

Purpose
-------
Analyze individual speech segments rather than diarization-label
prototypes.

This diagnostic is designed to answer:

1. Which segments have multiple strong voice neighbors?
2. Are those neighbors from the same Community-1 label?
3. Are they from different Community-1 labels?
4. Does a label contain multiple distinct voice neighborhoods?
5. Which cross-label relationships are actually supported by
   multiple independent observations?

IMPORTANT
---------
This is still diagnostic.

It does NOT:
    - modify production diarization
    - modify speaker_alignment.py
    - modify speaker_stabilization.py
    - modify Celery
    - force a speaker count
    - use transcript text
    - use grammar
    - rerun Community-1 diarization

It uses the embeddings already generated by speaker_identity.py.
"""


from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

import numpy as np


# ============================================================================
# CONFIGURATION
# ============================================================================

RECORDING_ID = 7

MIN_SEGMENT_DURATION = 1.5

# Strong voice similarity.
STRONG_SIMILARITY = 0.78

# Secondary supporting similarity.
SUPPORTING_SIMILARITY = 0.68

# Number of nearest neighbors examined for every segment.
TOP_K = 8

# Minimum number of strong neighbors required before a segment
# becomes an interesting identity anchor.
MIN_STRONG_NEIGHBORS = 2


# ============================================================================
# PATHS
# ============================================================================

BACKEND_DIR = Path(__file__).resolve().parents[2]

INPUT_PATH = (
    BACKEND_DIR
    / "storage"
    / "processed"
    / f"recording_{RECORDING_ID}"
    / "speaker_identity_diagnostic"
    / "speaker_identity_results.json"
)

OUTPUT_DIR = (
    BACKEND_DIR
    / "storage"
    / "processed"
    / f"recording_{RECORDING_ID}"
    / "speaker_identity_neighbors_diagnostic"
)

OUTPUT_PATH = (
    OUTPUT_DIR
    / "speaker_identity_neighbors_results.json"
)


# ============================================================================
# LOAD EMBEDDINGS
# ============================================================================


def load_results() -> dict[str, Any]:

    if not INPUT_PATH.exists():
        raise FileNotFoundError(
            f"Speaker identity result file not found:\n"
            f"{INPUT_PATH}"
        )

    with INPUT_PATH.open(
        "r",
        encoding="utf-8",
    ) as file:

        data = json.load(file)

    return data


# ============================================================================
# EMBEDDINGS
# ============================================================================


def load_embedding_matrix(
    data: dict[str, Any],
) -> tuple[
    list[dict[str, Any]],
    np.ndarray,
]:
    """
    The previous diagnostic intentionally did not save raw embeddings.

    Therefore this function checks whether they are available.

    If they are not, we will stop cleanly rather than inventing them.
    """

    raw_embeddings = data.get(
        "embeddings"
    )

    segments = data.get(
        "segments"
    )

    if not isinstance(
        segments,
        list,
    ):
        raise ValueError(
            "No segment list found in speaker identity results."
        )

    if not isinstance(
        raw_embeddings,
        list,
    ):
        raise ValueError(
            "Raw embeddings were not saved by the previous "
            "speaker_identity.py diagnostic.\n\n"
            "We need to update speaker_identity.py to save the "
            "91 embeddings before running this experiment."
        )

    if len(raw_embeddings) != len(segments):
        raise ValueError(
            f"Embedding count ({len(raw_embeddings)}) does not "
            f"match segment count ({len(segments)})."
        )

    matrix = np.asarray(
        raw_embeddings,
        dtype=np.float32,
    )

    if matrix.ndim != 2:
        raise ValueError(
            f"Unexpected embedding matrix shape: "
            f"{matrix.shape}"
        )

    return segments, matrix


# ============================================================================
# NORMALIZATION
# ============================================================================


def normalize_rows(
    matrix: np.ndarray,
) -> np.ndarray:

    norms = np.linalg.norm(
        matrix,
        axis=1,
        keepdims=True,
    )

    norms = np.maximum(
        norms,
        1e-12,
    )

    return matrix / norms


# ============================================================================
# NEAREST NEIGHBORS
# ============================================================================


def calculate_neighbors(
    segments: list[dict[str, Any]],
    embeddings: np.ndarray,
) -> list[dict[str, Any]]:

    embeddings = normalize_rows(
        embeddings
    )

    similarity_matrix = (
        embeddings @ embeddings.T
    )

    results = []

    for i, segment in enumerate(
        segments
    ):

        candidates = []

        for j in range(
            len(segments)
        ):

            if i == j:
                continue

            similarity = float(
                similarity_matrix[i, j]
            )

            candidates.append(
                {
                    "index": j,
                    "speaker": segments[j][
                        "speaker_label"
                    ],
                    "start": segments[j]["start"],
                    "end": segments[j]["end"],
                    "duration": segments[j]["duration"],
                    "similarity": similarity,
                }
            )

        candidates.sort(
            key=lambda item: item["similarity"],
            reverse=True,
        )

        top_neighbors = candidates[:TOP_K]

        strong_neighbors = [
            item
            for item in candidates
            if item["similarity"]
            >= STRONG_SIMILARITY
        ]

        supporting_neighbors = [
            item
            for item in candidates
            if item["similarity"]
            >= SUPPORTING_SIMILARITY
        ]

        results.append(
            {
                "index": i,
                "speaker": segment[
                    "speaker_label"
                ],
                "start": segment["start"],
                "end": segment["end"],
                "duration": segment["duration"],
                "strong_neighbor_count": len(
                    strong_neighbors
                ),
                "supporting_neighbor_count": len(
                    supporting_neighbors
                ),
                "top_neighbors": top_neighbors,
            }
        )

    return results


# ============================================================================
# PRINT ANCHORS
# ============================================================================


def print_anchor_segments(
    neighbors: list[dict[str, Any]],
) -> None:

    anchors = [
        item
        for item in neighbors
        if item["strong_neighbor_count"]
        >= MIN_STRONG_NEIGHBORS
    ]

    anchors.sort(
        key=lambda item: (
            item["strong_neighbor_count"],
            item["supporting_neighbor_count"],
        ),
        reverse=True,
    )

    print()
    print("=" * 80)
    print("STRONG IDENTITY ANCHORS")
    print("=" * 80)

    print(
        f"Segments with >= "
        f"{MIN_STRONG_NEIGHBORS} strong neighbors: "
        f"{len(anchors)}"
    )

    for anchor in anchors[:30]:

        print()
        print(
            f"[{anchor['index']:03d}] "
            f"{anchor['speaker']} "
            f"{anchor['start']:.2f}-"
            f"{anchor['end']:.2f} "
            f"({anchor['duration']:.2f}s)"
        )

        print(
            f"Strong neighbors: "
            f"{anchor['strong_neighbor_count']}"
        )

        print(
            f"Supporting neighbors: "
            f"{anchor['supporting_neighbor_count']}"
        )

        for neighbor in anchor[
            "top_neighbors"
        ]:

            print(
                f"    "
                f"{neighbor['speaker']} "
                f"{neighbor['start']:.2f}-"
                f"{neighbor['end']:.2f} "
                f"="
                f"{neighbor['similarity']:.4f}"
            )


# ============================================================================
# CROSS-LABEL SUPPORT
# ============================================================================


def calculate_cross_label_support(
    neighbors: list[dict[str, Any]],
) -> dict[
    tuple[str, str],
    dict[str, Any],
]:

    support = defaultdict(
        lambda: {
            "strong": 0,
            "supporting": 0,
            "best": -1.0,
            "examples": [],
        }
    )

    for item in neighbors:

        source_label = item[
            "speaker"
        ]

        for neighbor in item[
            "top_neighbors"
        ]:

            target_label = neighbor[
                "speaker"
            ]

            if (
                source_label
                == target_label
            ):
                continue

            pair = tuple(
                sorted(
                    [
                        source_label,
                        target_label,
                    ]
                )
            )

            similarity = neighbor[
                "similarity"
            ]

            record = support[pair]

            if similarity >= STRONG_SIMILARITY:
                record["strong"] += 1

            if similarity >= SUPPORTING_SIMILARITY:
                record["supporting"] += 1

            record["best"] = max(
                record["best"],
                similarity,
            )

            if len(
                record["examples"]
            ) < 10:

                record["examples"].append(
                    {
                        "source_label": source_label,
                        "source_start": item["start"],
                        "source_end": item["end"],
                        "target_label": target_label,
                        "target_start": neighbor["start"],
                        "target_end": neighbor["end"],
                        "similarity": similarity,
                    }
                )

    return dict(support)


# ============================================================================
# PRINT CROSS-LABEL SUPPORT
# ============================================================================


def print_cross_label_support(
    support: dict[
        tuple[str, str],
        dict[str, Any],
    ],
) -> None:

    rows = []

    for pair, record in support.items():

        rows.append(
            (
                pair,
                record,
            )
        )

    rows.sort(
        key=lambda item: (
            item[1]["strong"],
            item[1]["best"],
        ),
        reverse=True,
    )

    print()
    print("=" * 80)
    print("CROSS-LABEL IDENTITY SUPPORT")
    print("=" * 80)

    for pair, record in rows:

        print()
        print(
            f"{pair[0]} <-> {pair[1]}"
        )

        print(
            f"    strong matches: "
            f"{record['strong']}"
        )

        print(
            f"    supporting matches: "
            f"{record['supporting']}"
        )

        print(
            f"    best similarity: "
            f"{record['best']:.4f}"
        )

        for example in sorted(
            record["examples"],
            key=lambda item: item[
                "similarity"
            ],
            reverse=True,
        )[:5]:

            print(
                f"    "
                f"{example['source_label']} "
                f"{example['source_start']:.2f}-"
                f"{example['source_end']:.2f}"
                f" <-> "
                f"{example['target_label']} "
                f"{example['target_start']:.2f}-"
                f"{example['target_end']:.2f}"
                f" = "
                f"{example['similarity']:.4f}"
            )


# ============================================================================
# LABEL INTERNAL CONSISTENCY
# ============================================================================


def calculate_label_consistency(
    neighbors: list[dict[str, Any]],
) -> dict[str, dict[str, Any]]:

    data = defaultdict(
        lambda: {
            "segments": 0,
            "strong_same_label": 0,
            "strong_cross_label": 0,
            "supporting_same_label": 0,
            "supporting_cross_label": 0,
        }
    )

    for item in neighbors:

        label = item[
            "speaker"
        ]

        data[label]["segments"] += 1

        for neighbor in item[
            "top_neighbors"
        ]:

            similarity = neighbor[
                "similarity"
            ]

            same_label = (
                neighbor["speaker"]
                == label
            )

            if similarity >= STRONG_SIMILARITY:

                if same_label:
                    data[label][
                        "strong_same_label"
                    ] += 1
                else:
                    data[label][
                        "strong_cross_label"
                    ] += 1

            if similarity >= SUPPORTING_SIMILARITY:

                if same_label:
                    data[label][
                        "supporting_same_label"
                    ] += 1
                else:
                    data[label][
                        "supporting_cross_label"
                    ] += 1

    return dict(data)


def print_label_consistency(
    consistency: dict[str, dict[str, Any]],
) -> None:

    print()
    print("=" * 80)
    print("DIARIZATION LABEL CONSISTENCY")
    print("=" * 80)

    for label in sorted(
        consistency.keys()
    ):

        item = consistency[label]

        print()
        print(label)

        print(
            f"    segments: "
            f"{item['segments']}"
        )

        print(
            f"    strong same-label: "
            f"{item['strong_same_label']}"
        )

        print(
            f"    strong cross-label: "
            f"{item['strong_cross_label']}"
        )

        print(
            f"    supporting same-label: "
            f"{item['supporting_same_label']}"
        )

        print(
            f"    supporting cross-label: "
            f"{item['supporting_cross_label']}"
        )


# ============================================================================
# SAVE
# ============================================================================


def save_results(
    neighbors: list[dict[str, Any]],
    support: dict[
        tuple[str, str],
        dict[str, Any],
    ],
    consistency: dict[str, dict[str, Any]],
) -> None:

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    serialized_support = {}

    for pair, record in support.items():

        serialized_support[
            f"{pair[0]}__{pair[1]}"
        ] = record

    data = {
        "recording_id": RECORDING_ID,
        "configuration": {
            "strong_similarity": STRONG_SIMILARITY,
            "supporting_similarity": SUPPORTING_SIMILARITY,
            "top_k": TOP_K,
            "min_strong_neighbors": MIN_STRONG_NEIGHBORS,
        },
        "neighbor_analysis": neighbors,
        "cross_label_support": serialized_support,
        "label_consistency": consistency,
    }

    with OUTPUT_PATH.open(
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            data,
            file,
            indent=2,
        )

    print()
    print("=" * 80)
    print("RESULT")
    print("=" * 80)
    print()
    print("Saved:")
    print(OUTPUT_PATH)


# ============================================================================
# MAIN
# ============================================================================


def main() -> None:

    print()
    print("=" * 80)
    print("SPEAKER IDENTITY NEAREST-NEIGHBOR DIAGNOSTIC")
    print("=" * 80)

    print()
    print(
        "This diagnostic does not rerun diarization."
    )

    print(
        "This diagnostic does not modify production."
    )

    print()

    data = load_results()

    segments, embeddings = load_embedding_matrix(
        data
    )

    print(
        f"Segments: {len(segments)}"
    )

    print(
        f"Embedding matrix: {embeddings.shape}"
    )

    neighbors = calculate_neighbors(
        segments,
        embeddings,
    )

    print_anchor_segments(
        neighbors
    )

    support = calculate_cross_label_support(
        neighbors
    )

    print_cross_label_support(
        support
    )

    consistency = calculate_label_consistency(
        neighbors
    )

    print_label_consistency(
        consistency
    )

    save_results(
        neighbors,
        support,
        consistency,
    )

    print()
    print(
        "Nearest-neighbor diagnostic completed."
    )


if __name__ == "__main__":
    main()